def filtrar_temas_por_modo(modo):
    if modo == "claro":
        claves = [k for k in PALETAS if "(Claro)" in k]
    elif modo == "oscuro":
        claves = [k for k in PALETAS if "(Oscuro)" in k]
    elif modo == "clasico":
        claves = [k for k in PALETAS if "(Clasico)" in k]
    else:
        claves = list(PALETAS.keys())
    return [(k.rsplit(" (", 1)[0], k) for k in claves]

