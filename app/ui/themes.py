def normalizar_tema(nombre):
    """Migra claves de tema con la grafía antigua (sin tilde) a la actual."""
    if not nombre:
        return nombre
    return nombre.replace(" (Clasico)", " (Clásico)")

def _contraste_con_blanco(hex_color):
    """Contraste WCAG de un color contra blanco (4.5:1 para texto normal)."""
    def _lineal(c):
        c = c / 255.0
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    h = hex_color.lstrip("#")
    rgb = (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))
    luminancia = 0.2126 * _lineal(rgb[0]) + 0.7152 * _lineal(rgb[1]) + 0.0722 * _lineal(rgb[2])
    return (1.0 + 0.05) / (luminancia + 0.05)


def _luminancia(hex_color):
    def _lineal(c):
        c = c / 255.0
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
    h = hex_color.lstrip("#")
    rgb = (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))
    return 0.2126 * _lineal(rgb[0]) + 0.7152 * _lineal(rgb[1]) + 0.0722 * _lineal(rgb[2])


def _contraste(a, b):
    la, lb = _luminancia(a), _luminancia(b)
    return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)


def _oscurcer_hasta(hex_color, ratio_minimo, superficies):
    """Oscurece el color hasta contrastar >= ratio con todas las superficies."""
    h = hex_color.lstrip("#")
    rgb = (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))
    factor = 0.99
    while factor > 0.0:
        c = "#{:02X}{:02X}{:02X}".format(*(int(v * factor) for v in rgb))
        if all(_contraste(c, s) >= ratio_minimo for s in superficies):
            return c
        factor -= 0.02
    return "#000000"


def _aclarar_hasta(hex_color, ratio_minimo, superficies):
    """Aclara el color (hacia blanco) hasta contrastar >= ratio con todas las superficies."""
    h = hex_color.lstrip("#")
    rgb = (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))
    factor = 0.01
    while factor <= 1.0:
        c = "#{:02X}{:02X}{:02X}".format(*(int(v + (255 - v) * factor) for v in rgb))
        if all(_contraste(c, s) >= ratio_minimo for s in superficies):
            return c
        factor += 0.02
    return "#FFFFFF"


def _tinta_hover(t):
    """Tinta legible (>= 4.5:1) para hover de controles secundarios sobre las superficies.

    Prefiere `resaltado` o `acento` cuando ya cumplen; si no, aclara el acento en
    familias oscuras o lo oscurece en familias claras, manteniendo la familia de color.
    """
    superficies = (t["fondo"], t["fondo_input"])
    for candidato in (t["resaltado"], t["acento"]):
        if all(_contraste(candidato, s) >= 4.5 for s in superficies):
            return candidato
    if _luminancia(t["fondo"]) > 0.4:
        return _oscurcer_hasta(t["acento"], 4.5, superficies)
    return _aclarar_hasta(t["resaltado"], 4.5, superficies)


def _acento_para_boton(hex_color, ratio_minimo=4.5):
    """Acento de relleno para botones primarios con contraste garantizado contra blanco.

    Si el acento de la paleta es demasiado claro para texto blanco, devuelve una derivada
    oscura del mismo acento (misma familia, contraste >= `ratio_minimo`:1). El acento
    original se conserva intacto para texto, hover y selección.
    """
    h = hex_color.lstrip("#")
    rgb = (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))
    if _contraste_con_blanco(hex_color) >= ratio_minimo:
        return hex_color
    factor = 0.98
    while factor > 0.0:
        oscuro = tuple(int(c * factor) for c in rgb)
        oscuro_hex = "#{:02X}{:02X}{:02X}".format(*oscuro)
        if _contraste_con_blanco(oscuro_hex) >= ratio_minimo:
            return oscuro_hex
        factor -= 0.02
    return "#000000"


